-- Flytrace schema, milestone 1.
-- Column semantics follow the original MSSQL DDL in db/legacy/orig-mssql-db-script.sql.
-- All legacy datetime values were stored as UTC, hence timestamptz throughout.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username                citext NOT NULL UNIQUE,
  email                   citext UNIQUE,             -- also accepted as a login name; NULLs may repeat
  -- Either "flytrace1|<base64 sha1>|<format>|<base64 salt>" (legacy ASP.NET membership)
  -- or a modern "$argon2id$..." string. Legacy hashes are upgraded on first successful login.
  password_hash           text NOT NULL,
  is_approved             boolean NOT NULL DEFAULT true,
  is_locked_out           boolean NOT NULL DEFAULT false,
  created_at              timestamptz NOT NULL DEFAULT now(),
  last_login_at           timestamptz,
  legacy_last_activity_at timestamptz,
  -- Accounts that exist already (imported from the old site, or made by the CLI) count as confirmed;
  -- registration sets it to false explicitly.
  email_confirmed           boolean NOT NULL DEFAULT true,
  two_factor_enabled        boolean NOT NULL DEFAULT false,
  two_factor_secret         text,    -- base32 TOTP secret, set while two_factor_enabled
  two_factor_last_used_step bigint,  -- last accepted 30 s time step, so a code works only once
  CONSTRAINT users_two_factor_secret_chk CHECK (NOT two_factor_enabled OR two_factor_secret IS NOT NULL)
);

CREATE TABLE roles (
  id   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name citext NOT NULL UNIQUE
);

CREATE TABLE user_roles (
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role_id uuid NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, role_id)
);
CREATE INDEX user_roles_role_id_idx ON user_roles (role_id);

CREATE TABLE events (
  id       integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id  uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name     varchar(256) NOT NULL,
  start_ts timestamptz                                -- "hide old points" cut-off
);
CREATE INDEX events_user_id_idx ON events (user_id);
CREATE UNIQUE INDEX events_user_id_name_key ON events (user_id, name);

CREATE TABLE user_profiles (
  user_id                       uuid PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  default_event_id              integer REFERENCES events (id) ON DELETE SET NULL,
  is_simple_events_model        boolean NOT NULL DEFAULT true,
  coord_format                  varchar(50) NOT NULL DEFAULT 'Deg'
                                CHECK (coord_format IN ('Deg', 'DegMin', 'DegMinSec')),
  def_hemisphere_ns             char(1) NOT NULL DEFAULT 'N' CHECK (def_hemisphere_ns IN ('N', 'S')),
  def_hemisphere_ew             char(1) NOT NULL DEFAULT 'E' CHECK (def_hemisphere_ew IN ('E', 'W')),
  show_user_messages_by_default boolean NOT NULL DEFAULT true,
  user_messages_setting_is_new  boolean NOT NULL DEFAULT false,
  altitude_unit                 varchar(20) CHECK (altitude_unit IN ('m', 'ft'))  -- NULL = don't show
);
CREATE INDEX user_profiles_default_event_id_idx ON user_profiles (default_event_id);

CREATE TABLE groups (
  id                    integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name                  varchar(256) NOT NULL,
  user_id               uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  event_id              integer REFERENCES events (id) ON DELETE SET NULL,
  newest_coord_ts       timestamptz,
  newest_lat            double precision,
  newest_lon            double precision,
  views_num             integer NOT NULL DEFAULT 0,
  page_updates_num      bigint NOT NULL DEFAULT 0,
  is_public             boolean NOT NULL DEFAULT false,
  version               integer NOT NULL DEFAULT 0,   -- bumped on tracker list changes
  display_user_messages boolean NOT NULL DEFAULT false
);
CREATE INDEX groups_user_id_idx ON groups (user_id);
CREATE INDEX groups_public_newest_idx ON groups (is_public, newest_coord_ts DESC);
CREATE UNIQUE INDEX groups_user_id_name_key ON groups (user_id, name);
CREATE INDEX groups_event_id_idx ON groups (event_id);

CREATE TABLE group_trackers (
  id                   integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  group_id             integer NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
  name                 varchar(50) NOT NULL,
  tracker_type         char(1) NOT NULL CHECK (tracker_type IN ('S', 'G', 'T')), -- SPOT, Garmin inReach, test
  foreign_id           varchar(445) NOT NULL,           -- SPOT feed id or Garmin MapShare URL
  foreign_id_as_entered varchar(445),
  is_on                boolean NOT NULL DEFAULT true
);
CREATE INDEX group_trackers_group_id_idx ON group_trackers (group_id);
CREATE UNIQUE INDEX group_trackers_group_id_name_key ON group_trackers (group_id, name);
CREATE UNIQUE INDEX group_trackers_group_id_feed_key ON group_trackers (group_id, tracker_type, foreign_id);

CREATE TABLE waypoints (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  event_id    integer NOT NULL REFERENCES events (id) ON DELETE CASCADE,
  name        varchar(50) NOT NULL,
  lat         double precision NOT NULL,
  lon         double precision NOT NULL,
  alt         double precision NOT NULL,
  description varchar(500)
);
CREATE INDEX waypoints_event_id_idx ON waypoints (event_id);
CREATE UNIQUE INDEX waypoints_event_id_name_key ON waypoints (event_id, name);

CREATE TABLE tasks (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  waypoint_id integer NOT NULL REFERENCES waypoints (id) ON DELETE CASCADE,
  radius      integer NOT NULL,
  wpt_order   integer NOT NULL
);
CREATE INDEX tasks_waypoint_id_idx ON tasks (waypoint_id);

-- Session store table in the shape connect-pg-simple expects.
CREATE TABLE sessions (
  sid    varchar NOT NULL PRIMARY KEY,
  sess   json NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX sessions_expire_idx ON sessions (expire);

-- One-time links sent by email. Only the SHA-256 of the token is stored, so a database leak does not
-- give out working links.
CREATE TABLE user_tokens (
  id         bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  purpose    text NOT NULL CHECK (purpose IN ('confirm_email', 'reset_password', 'change_email')),
  token_hash text NOT NULL UNIQUE,
  data       text,                       -- change_email: the new address
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  used_at    timestamptz
);
CREATE INDEX user_tokens_user_id_idx ON user_tokens (user_id);

-- Single-use backup codes for when the authenticator app is not at hand (SHA-256 of the code).
CREATE TABLE recovery_codes (
  user_id   uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  code_hash text NOT NULL,
  used_at   timestamptz,
  PRIMARY KEY (user_id, code_hash)
);

